'use strict';

const fs = require('fs').promises;
const path = require('path');
const logger = require('../utils/logger');

const SUPPORTED_FORMATS = ['html', 'markdown', 'json', 'javascript'];

class OutputGenerator {
  constructor(config = {}) {
    this.rootDir = config.rootDir || process.cwd();
    this.outputDir = path.resolve(this.rootDir, config.outputDir || 'output');
  }

  /**
   * Pure renderer: returns the document as a string, never touches disk.
   */
  render(news = [], format = 'json', context = {}) {
    switch (format) {
      case 'html':
        return this.renderHTML(news, context);
      case 'markdown':
        return this.renderMarkdown(news, context);
      case 'javascript':
        return this.renderJavaScript(news, context);
      case 'json':
        return JSON.stringify({ generatedAt: new Date().toISOString(), ...context, articles: news }, null, 2);
      default:
        throw new Error(`Unsupported format "${format}". Supported: ${SUPPORTED_FORMATS.join(', ')}`);
    }
  }

  /**
   * Render and persist to output/. Returns { format, path, content }.
   */
  async generate(news = [], format = 'html', context = {}) {
    const content = this.render(news, format, context);
    const extension = format === 'javascript' ? 'js' : format === 'markdown' ? 'md' : format;

    await fs.mkdir(this.outputDir, { recursive: true });
    const fileName = `ai-radar-${stamp()}.${extension}`;
    const filePath = path.join(this.outputDir, fileName);
    await fs.writeFile(filePath, content, 'utf8');

    logger.info('Output written', { format, file: fileName, articles: news.length });
    return { format, path: filePath, content };
  }

  renderHTML(news, context = {}) {
    const title = context.title || 'Smart AI Radar';
    const subtitle = context.subtitle || '为你定制的 AI 资讯雷达';

    const cards = news
      .map((article) => {
        const tags = (article.tags || [])
          .slice(0, 4)
          .map((tag) => `<span class="tag">${escapeHTML(tag)}</span>`)
          .join('');

        return `      <article class="card">
        <h2><a href="${escapeAttribute(article.url)}" target="_blank" rel="noopener noreferrer">${escapeHTML(article.title)}</a></h2>
        <p class="meta">${escapeHTML(article.source || '')} · ${formatDate(article.publishedAt)} · 相关度 ${(article.relevance * 100).toFixed(0)}%</p>
        ${article.summary ? `<p class="summary">${escapeHTML(article.summary)}</p>` : ''}
        ${tags ? `<p class="tags">${tags}</p>` : ''}
      </article>`;
      })
      .join('\n');

    return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHTML(title)}</title>
  <style>
    :root { color-scheme: light dark; --fg:#1a1a1a; --muted:#666; --bg:#f6f7f9; --card:#fff; --line:#e3e6ea; --accent:#2563eb; }
    @media (prefers-color-scheme: dark) {
      :root { --fg:#e8eaed; --muted:#9aa0a6; --bg:#111318; --card:#1a1d23; --line:#2a2e37; --accent:#7aa2ff; }
    }
    * { box-sizing: border-box; }
    body { margin:0; padding:32px 20px 64px; background:var(--bg); color:var(--fg);
           font:16px/1.6 -apple-system, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif; }
    .wrap { max-width: 780px; margin: 0 auto; }
    header { margin-bottom: 28px; }
    h1 { margin: 0 0 6px; font-size: 1.9rem; letter-spacing: -0.02em; }
    .subtitle { margin: 0; color: var(--muted); font-size: 0.95rem; }
    .card { background: var(--card); border: 1px solid var(--line); border-radius: 12px;
            padding: 18px 20px; margin-bottom: 14px; }
    .card h2 { margin: 0 0 6px; font-size: 1.1rem; line-height: 1.4; }
    .card h2 a { color: var(--fg); text-decoration: none; }
    .card h2 a:hover { color: var(--accent); text-decoration: underline; }
    .meta { margin: 0 0 10px; color: var(--muted); font-size: 0.82rem; }
    .summary { margin: 0; color: var(--fg); opacity: 0.86; font-size: 0.94rem; }
    .tags { margin: 10px 0 0; display: flex; flex-wrap: wrap; gap: 6px; }
    .tag { font-size: 0.72rem; color: var(--accent); background: color-mix(in srgb, var(--accent) 12%, transparent);
           border-radius: 999px; padding: 2px 9px; }
    footer { margin-top: 32px; color: var(--muted); font-size: 0.78rem; text-align: center; }
    footer a { color: inherit; }
  </style>
</head>
<body>
  <div class="wrap">
    <header>
      <h1>${escapeHTML(title)}</h1>
      <p class="subtitle">${escapeHTML(subtitle)} · ${news.length} 条 · 生成于 ${formatDate(new Date().toISOString())}</p>
    </header>
${cards || '    <p class="subtitle">当前筛选条件下没有匹配的资讯。</p>'}
    <footer>Generated by <a href="https://github.com/stonearro/smart-ai-radar">smart-ai-radar</a></footer>
  </div>
</body>
</html>
`;
  }

  renderMarkdown(news, context = {}) {
    const title = context.title || 'Smart AI Radar';
    const lines = [`# ${title}`, '', `> ${news.length} 条资讯 · 生成于 ${formatDate(new Date().toISOString())}`, ''];

    if (context.persona) {
      lines.push(`**Persona:** \`${context.persona}\``, '');
    }

    if (news.length === 0) {
      lines.push('_当前筛选条件下没有匹配的资讯。_', '');
      return lines.join('\n');
    }

    for (const article of news) {
      lines.push(`## [${article.title}](${article.url})`);
      lines.push('');
      lines.push(
        `*${article.source || '未知来源'}* · ${formatDate(article.publishedAt)} · 相关度 ${(article.relevance * 100).toFixed(0)}%`
      );
      lines.push('');

      if (article.summary) {
        lines.push(article.summary, '');
      }

      if (article.tags && article.tags.length > 0) {
        lines.push(article.tags.map((tag) => `\`${tag}\``).join(' '), '');
      }

      lines.push('---', '');
    }

    return lines.join('\n');
  }

  /**
   * Standalone script that renders the radar into any page:
   *   <div id="ai-radar"></div><script src="ai-radar-xxx.js"></script>
   */
  renderJavaScript(news, context = {}) {
    const payload = JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        title: context.title || 'Smart AI Radar',
        persona: context.persona || null,
        articles: news
      },
      null,
      2
    );

    return `/* smart-ai-radar bundle — https://github.com/stonearro/smart-ai-radar */
(function (global) {
  'use strict';

  var DATA = ${payload};

  function escapeHTML(value) {
    return String(value == null ? '' : value).replace(/[&<>"']/g, function (character) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character];
    });
  }

  function render(target) {
    var host = typeof target === 'string' ? document.querySelector(target) : target;
    if (!host) return null;

    host.innerHTML = DATA.articles.map(function (article) {
      return '<article class="ai-radar-card">' +
        '<h2><a href="' + escapeHTML(article.url) + '" target="_blank" rel="noopener noreferrer">' +
        escapeHTML(article.title) + '</a></h2>' +
        '<p class="ai-radar-meta">' + escapeHTML(article.source) + ' · ' +
        escapeHTML(article.publishedAt || '') + ' · 相关度 ' +
        Math.round((article.relevance || 0) * 100) + '%</p>' +
        (article.summary ? '<p>' + escapeHTML(article.summary) + '</p>' : '') +
        '</article>';
    }).join('');

    return host;
  }

  global.SmartAIRadar = { data: DATA, render: render };
})(typeof window !== 'undefined' ? window : globalThis);
`;
  }

  static get supportedFormats() {
    return [...SUPPORTED_FORMATS];
  }
}

/* ------------------------------ helpers ------------------------------ */

function stamp() {
  return new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
}

function formatDate(value) {
  if (!value) return '时间未知';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '时间未知';
  return `${date.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
}

function escapeHTML(value) {
  return String(value == null ? '' : value).replace(/[&<>"']/g, (character) => {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character];
  });
}

function escapeAttribute(value) {
  const url = String(value == null ? '' : value).trim();
  if (!/^https?:\/\//i.test(url)) return '#';
  return escapeHTML(url);
}

module.exports = { OutputGenerator, SUPPORTED_FORMATS };
